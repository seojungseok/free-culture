const assert = require("node:assert/strict");
const fs = require("node:fs"), path = require("node:path"), Module = require("node:module"), ts = require("typescript");
const root = path.resolve(__dirname, "..");
const resolve = Module._resolveFilename;
Module._resolveFilename = function(request, parent, ...args) { return resolve.call(this, request.startsWith("@/") ? path.join(root, request.slice(2)) : request, parent, ...args); };
Module._extensions[".ts"] = (module, filename) => module._compile(ts.transpileModule(fs.readFileSync(filename,"utf8"), { compilerOptions: { module: ts.ModuleKind.CommonJS, target: ts.ScriptTarget.ES2020, esModuleInterop: true } }).outputText, filename);
const { visitChecks, placeFacilityFees } = require("../lib/visitPlanning.ts");
const facilityData = require("../data/place-info.json").info["809490"];
const separated = placeFacilityFees(facilityData);
assert.equal(separated.admission, "무료", "입장료는 앞선 주차요금과 구분해야 한다");
assert.match(separated.parking, /최초 30분/);
const checks = visitChecks({kind:"place", fee:separated.admission, parking:"가능", parkingFee:separated.parking});
assert.equal(checks.find((item) => item.id === "fee").detail, "요금 안내: 무료");
assert.match(checks.find((item) => item.id === "parking").detail, /주차요금: 최초 30분/);
assert.equal(placeFacilityFees([{name:"주차 요금",text:"유료"}]).admission, undefined);
assert.equal(placeFacilityFees([{name:"기타 요금",text:"확인"}]).admission, undefined);
assert(visitChecks({kind:"place", parkingFee:"유료"}).some((item) => item.id === "parking"));
const missing = visitChecks({kind:"place", hours:"정보 없음", fee:"0", parking:"null"});
assert(missing.find((item) => item.id === "schedule").detail.includes("안내가 없습니다"));
assert(!missing.some((item) => item.id === "parking"));
const mixedFee = "입장 무료, 체험 5,000원";
assert(visitChecks({kind:"place", fee:mixedFee}).find((item) => item.id === "fee").detail.includes(mixedFee));
const camp = visitChecks({kind:"camp", facilities:[], pet:"불가능"});
assert(camp.find((item) => item.id === "facilities").detail.includes("제공 여부를 확인"));
assert(camp.find((item) => item.id === "pet").detail.includes("불가능"));
assert(!JSON.stringify(camp).includes("제공하지 않"));
const food = visitChecks({kind:"food", menu:"추탕", hours:"11:00~22:00"});
assert(food.find((item)=>item.id==="menu").detail.includes("추탕"));
assert(!JSON.stringify(food).includes("맛있"));
const ids = camp.map((item)=>item.id);
assert.equal(new Set(ids).size, ids.length);
console.log("PASS: missing facts, mixed fees, facility uncertainty, pet restrictions and food menu preserved.");
